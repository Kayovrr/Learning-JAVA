package Introducao_Java.Arrays;

public class Listas2 {
    public static void main(String[] args){
        // tipos de padrão de inicialização
        // byte, short, int, long, float, double é 0
        // char é '\u0000'
        // boolean é false
        // String é null

        int[] variavel0 = new int[3];
        System.out.println(variavel0[0]);

        char[] variavel1 = new char[3];
        System.out.println(variavel1[0]);

        boolean[] variavel2 = new boolean[3];
        System.out.println(variavel2[0]);

        String[] variavel3 = new String[3];
        System.out.println(variavel3[0]);

    }
}
